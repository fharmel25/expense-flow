using ExpenseFlow.Domain.Common;
using ExpenseFlow.Domain.Enums;

namespace ExpenseFlow.Domain.Entities;

public class Expense
{
    public const int MaxDescriptionLength = 500;
    public const int MaxReasonLength = 500;
    public const decimal MaxAmount = 9_999_999_999.99m; // fits decimal(12,2)

    private readonly List<ExpenseHistory> _history = new();

    public Guid Id { get; private set; }
    public Guid EmployeeId { get; private set; }
    public User Employee { get; private set; } = default!;
    public decimal Amount { get; private set; }
    public string Currency { get; private set; } = default!;
    public ExpenseCategory Category { get; private set; }
    public string? Description { get; private set; }
    public DateOnly ExpenseDate { get; private set; }
    public string ReceiptBlobName { get; private set; } = default!;
    public ExpenseStatus Status { get; private set; }
    public string? WorkflowInstanceId { get; private set; }
    public DateTime SubmittedAt { get; private set; }
    public DateTime? DecidedAt { get; private set; }
    public Guid? DecidedById { get; private set; }
    public string? RejectionReason { get; private set; }
    public IReadOnlyCollection<ExpenseHistory> History => _history.AsReadOnly();

    private Expense() { } // required by EF Core

    /// <summary>
    /// An employee submits an expense. The id is generated by the app so that a retry
    /// of the same submission does not create a duplicate (idempotency).
    /// </summary>
    public static Expense Submit(Guid id, Guid employeeId, decimal amount, string currency, ExpenseCategory category,
        string? description, DateOnly expenseDate, string receiptBlobName, DateTime utcNow)
    {
        UtcGuard.Ensure(utcNow);
        if (id == Guid.Empty) throw new DomainException("Expense id is required.");
        if (employeeId == Guid.Empty) throw new DomainException("Employee id is required.");
        if (amount <= 0) throw new DomainException("Amount must be greater than zero.");
        if (amount > MaxAmount) throw new DomainException("Amount is too large.");
        if (decimal.Round(amount, 2) != amount) throw new DomainException("Amount can have at most 2 decimals.");
        if (string.IsNullOrWhiteSpace(currency) || currency.Trim().Length != 3)
            throw new DomainException("Currency must be a 3-letter code (e.g. EUR).");
        if (string.IsNullOrWhiteSpace(receiptBlobName)) throw new DomainException("A receipt is required.");
        if (description?.Length > MaxDescriptionLength)
            throw new DomainException($"Description cannot exceed {MaxDescriptionLength} characters.");
        if (expenseDate > DateOnly.FromDateTime(utcNow))
            throw new DomainException("Expense date cannot be in the future.");

        var expense = new Expense
        {
            Id = id,
            EmployeeId = employeeId,
            Amount = amount,
            Currency = currency.Trim().ToUpperInvariant(),
            Category = category,
            Description = description?.Trim(),
            ExpenseDate = expenseDate,
            ReceiptBlobName = receiptBlobName,
            Status = ExpenseStatus.Submitted,
            SubmittedAt = utcNow
        };
        expense._history.Add(new ExpenseHistory(expense.Id, null, ExpenseStatus.Submitted, employeeId, utcNow, null));
        return expense;
    }

    /// <summary>Called by the workflow: Submitted → InReview.</summary>
    public void StartReview(DateTime utcNow)
    {
        EnsureStatus(ExpenseStatus.Submitted, "start the review of");
        ChangeStatus(ExpenseStatus.InReview, changedById: null, utcNow, comment: null);
    }

    public void Approve(Guid managerId, DateTime utcNow)
    {
        EnsureStatus(ExpenseStatus.InReview, "approve");
        EnsureNotSelfDecision(managerId);
        DecidedById = managerId;
        DecidedAt = utcNow;
        ChangeStatus(ExpenseStatus.Approved, managerId, utcNow, comment: null);
    }

    public void Reject(Guid managerId, string reason, DateTime utcNow)
    {
        EnsureStatus(ExpenseStatus.InReview, "reject");
        EnsureNotSelfDecision(managerId);
        if (string.IsNullOrWhiteSpace(reason)) throw new DomainException("A rejection reason is required.");
        if (reason.Length > MaxReasonLength)
            throw new DomainException($"Reason cannot exceed {MaxReasonLength} characters.");

        RejectionReason = reason.Trim();
        DecidedById = managerId;
        DecidedAt = utcNow;
        ChangeStatus(ExpenseStatus.Rejected, managerId, utcNow, RejectionReason);
    }

    /// <summary>Links the Elsa workflow. Only once, to prevent duplicate workflows.</summary>
    public void AttachWorkflow(string workflowInstanceId)
    {
        if (string.IsNullOrWhiteSpace(workflowInstanceId)) throw new DomainException("Workflow instance id is required.");
        if (WorkflowInstanceId is not null) throw new InvalidStatusTransitionException("A workflow is already attached to this expense.");
        WorkflowInstanceId = workflowInstanceId;
    }

    private void EnsureStatus(ExpenseStatus expected, string action)
    {
        if (Status != expected)
            throw new InvalidStatusTransitionException($"Cannot {action} an expense with status {Status}.");
    }

    private void EnsureNotSelfDecision(Guid managerId)
    {
        if (managerId == EmployeeId) throw new DomainException("You cannot decide on your own expense.");
    }

    private void ChangeStatus(ExpenseStatus to, Guid? changedById, DateTime utcNow, string? comment)
    {
        UtcGuard.Ensure(utcNow);
        var from = Status;
        Status = to;
        _history.Add(new ExpenseHistory(Id, from, to, changedById, utcNow, comment));
    }
}
